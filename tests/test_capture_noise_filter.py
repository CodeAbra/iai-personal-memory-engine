def test_hook_drops_local_command_sequence_and_meta(tmp_path: Path):
    """The inline hook must spool ONLY the genuine prompts around a /model switch."""
    sid = "noise-filter-hook-session"
    home = tmp_path
    (home / ".iai-mcp" / ".capture-state").mkdir(parents=True)
    (home / ".iai-mcp" / ".deferred-captures").mkdir(parents=True)
    transcript = home / "transcript.jsonl"
    caveat = (
        "<local-command-caveat>Caveat: The messages below were generated by the "
        "user while running local commands. DO NOT respond to these messages or "
        "otherwise consider them in your response unless the user explicitly asks "
        "you to.</local-command-caveat>"
    )
    lines = [
        _user_line("why is the working tier goal polluted after a model switch",
                   uuid="u1", timestamp="2026-08-17T16:22:43.911Z"),
        _user_line("[Request interrupted by user]", uuid="u2",
                   timestamp="2026-08-17T16:23:06.000Z"),
        _user_line(caveat, uuid="u3", timestamp="2026-08-17T16:23:08.000Z", isMeta=True),
        _user_line("<command-name>/model</command-name>\n            <command-message>"
                   "model</command-message>\n            <command-args>claude-opus-4-8"
                   "</command-args>", uuid="u4", timestamp="2026-08-17T16:23:08.000Z"),
        _user_line("<local-command-stdout>Set model to claude-opus-4-8"
                   "</local-command-stdout>", uuid="u5",
                   timestamp="2026-08-17T16:23:08.000Z"),
        _user_line("fix the injection", uuid="u6", timestamp="2026-08-17T16:23:35.000Z"),
    ]
    transcript.write_text("\n".join(lines) + "\n")

    env = dict(os.environ, HOME=str(home))
    proc = subprocess.run(
        [sys.executable, "-c", _hook_py_script(), sid, str(transcript)],
        env=env, capture_output=True, text=True, timeout=30,
    )
    assert proc.returncode == 0, proc.stderr

    live = home / ".iai-mcp" / ".deferred-captures" / f"{sid}.live.jsonl"
    events = [json.loads(ln) for ln in live.read_text().splitlines() if ln.strip()]
    turns = [e for e in events if "role" in e]
    assert [t["text"] for t in turns] == [
        "why is the working tier goal polluted after a model switch",
        "fix the injection",
    ], turns
    assert [t["source_uuid"] for t in turns] == ["u1", "u6"]


