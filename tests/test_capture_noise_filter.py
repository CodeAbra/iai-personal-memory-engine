from iai_mcp.capture import _NOISE_PATTERNS, _parse_transcript_line

HOOK_FILE = (
    Path(__file__).resolve().parent.parent
    / "src" / "iai_mcp" / "_deploy" / "hooks" / "iai-mcp-turn-capture.sh"
)


def _user_line(text: str, **extra) -> str:
    obj = {"type": "user", "message": {"role": "user", "content": text}}
    obj.update(extra)
    return json.dumps(obj)


def _hook_py_script() -> str:
    m = re.search(r"PY_SCRIPT='(.*?)'\s*\n", HOOK_FILE.read_text(), re.DOTALL)
    assert m, f"PY_SCRIPT heredoc not found in {HOOK_FILE}"
    return m.group(1)


def _hook_noise_tuples() -> tuple[tuple[str, ...], tuple[str, ...]]:
    tree = ast.parse(_hook_py_script())
    found: dict[str, tuple[str, ...]] = {}
    for node in ast.walk(tree):
        if not isinstance(node, ast.Assign) or len(node.targets) != 1:
            continue
        target = node.targets[0]
        if isinstance(target, ast.Name) and target.id in ("_NOISE_STARTSWITH", "_NOISE_EQUALS"):
            found[target.id] = tuple(ast.literal_eval(node.value))
    assert set(found) == {"_NOISE_STARTSWITH", "_NOISE_EQUALS"}, found
    return found["_NOISE_STARTSWITH"], found["_NOISE_EQUALS"]


def test_hook_noise_filter_mirrors_capture():
    hook_prefixes, hook_exacts = _hook_noise_tuples()
    capture_prefixes = tuple(p for kind, p in _NOISE_PATTERNS if kind == "startswith")
    capture_exacts = tuple(p for kind, p in _NOISE_PATTERNS if kind == "equals")
    assert hook_prefixes == capture_prefixes, (
        "hook _NOISE_STARTSWITH drifted from capture._NOISE_PATTERNS"
    )
    assert hook_exacts == capture_exacts, (
        "hook _NOISE_EQUALS drifted from capture._NOISE_PATTERNS"
    )


