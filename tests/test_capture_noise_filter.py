# ---------------------------------------------------------------------------
# Immediate-path noise: the raw-slash guard — a slash-command prompt arrives
# as RAW text on stdin (`/command`), not expanded <command-*> markup — plus
# the existing _is_noise mirror.
# ---------------------------------------------------------------------------

def _immediate_payload_run(tmp_path: Path, sid: str, prompt: str, prompt_id: str) -> list[dict]:
    home = tmp_path / f"home-imm-{sid}"
    (home / ".iai-mcp" / ".capture-state").mkdir(parents=True)
    (home / ".iai-mcp" / ".deferred-captures").mkdir(parents=True)
    # Filler transcript line: keeps this helper representative of the
    # common case where a transcript already exists alongside the immediate
    # capture. First-fire (no transcript at all) is covered separately.
    transcript = home / "transcript.jsonl"
    transcript.write_text(_user_line("unrelated filler turn for transcript resolution") + "\n")
    payload = home / "payload.json"
    payload.write_text(json.dumps({"prompt": prompt, "prompt_id": prompt_id}), encoding="utf-8")

    env = dict(os.environ, HOME=str(home))
    proc = subprocess.run(
        [sys.executable, "-c", _hook_py_script(), sid, str(transcript), str(payload), prompt_id],
        env=env, capture_output=True, text=True, timeout=30,
    )
    assert proc.returncode == 0, proc.stderr

    live = home / ".iai-mcp" / ".deferred-captures" / f"{sid}.live.jsonl"
    events = [json.loads(ln) for ln in live.read_text().splitlines() if ln.strip()]
    return [e for e in events if "role" in e]


def test_immediate_path_drops_raw_slash_command(tmp_path: Path):
    prompt = "/deploy extra padding so length clears the floor"
    prompt_id = "slash-guard-prompt-id-0001"
    turns = _immediate_payload_run(tmp_path, "slash-guard-hook", prompt, prompt_id)
    # only the unrelated filler turn from the transcript walk, no immediate line
    assert not any(t.get("source_uuid") == prompt_id for t in turns), (
        "a raw leading-slash prompt must not reach the immediate spool — "
        "the stdin prompt for a /command arrives RAW (confirmed live), "
        "not expanded <command-*> markup"
    )


def test_immediate_path_writes_genuine_prompt(tmp_path: Path):
    prompt = "please tighten the immediate capture path for this real test"
    prompt_id = "genuine-immediate-prompt-id-0002"
    turns = _immediate_payload_run(tmp_path, "genuine-immediate-hook", prompt, prompt_id)
    matches = [t for t in turns if t.get("source_uuid") == prompt_id]
    assert len(matches) == 1, turns
    assert matches[0]["text"] == prompt
    assert matches[0]["role"] == "user"


# ---------------------------------------------------------------------------
# Convergence-point guard: capture_turn() itself rejects structural noise on
# EVERY route (RPC, CLI, drain workers), not only the transcript-parse walk
# above. The recorded pollution signature is a query-generation eval
# harness's own prompt template header -- structural scaffolding, not any
# specific leaked phrase a user typed.
# ---------------------------------------------------------------------------

REAL_POLLUTION_SIGNATURE = (
    "Below is one record from a developer's personal memory system.\n\n"
    "Write the single most natural short query this person would type to "
    "pull this exact record back out by MEANING alone. Do not copy "
    "identifiers/paths/version numbers."
)


def _select_driver(driver: str, monkeypatch) -> None:
    if driver == "lilli":
        try:
            import iai_mcp_native  # noqa: F401
        except ImportError:
            pytest.skip("iai_mcp_native not built — lilli driver unavailable in this env")
        monkeypatch.setenv("LILLI_STORAGE_DRIVER", "lilli")
    else:
        monkeypatch.delenv("LILLI_STORAGE_DRIVER", raising=False)


@pytest.mark.parametrize("driver", ["stdlib", "lilli"])
def test_capture_turn_rejects_the_real_recorded_pollution_signature(
    driver, tmp_path: Path, monkeypatch,
):
    """The exact eval-harness template shape recorded as the live pollution
    instance, fed through the REAL capture_turn(), must be rejected as a
    skip-shaped result and write no record."""
    _select_driver(driver, monkeypatch)
    from iai_mcp.capture import capture_turn
    from iai_mcp.store import MemoryStore

    store = MemoryStore(path=tmp_path / "lancedb")
    result = capture_turn(
        store, cue="c", text=REAL_POLLUTION_SIGNATURE,
        session_id="s-noise-real", role="user",
    )

    assert result["status"] == "skipped", result
    assert result["record_id"] is None
    assert list(store.iter_records()) == []


